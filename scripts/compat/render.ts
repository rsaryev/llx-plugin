import type { Proof } from './junit.ts';
import type { Requirement, RequirementsFile } from '../spec/requirements.ts';
import { CATEGORIES, type Category } from '../spec/sources.ts';

/** A requirement's standing in a test run. */
type Standing = 'proven' | 'failing' | 'unproven';

const standingOf = (proof: Proof | undefined): Standing =>
  !proof || proof.tests === 0 ? 'unproven' : proof.failures > 0 ? 'failing' : 'proven';

const percent = (part: number, whole: number): string =>
  whole === 0 ? '0.0%' : `${((100 * part) / whole).toFixed(1)}%`;

interface Row {
  readonly category: Category;
  readonly total: number;
  readonly proven: number;
  readonly failing: readonly Requirement[];
  readonly unproven: readonly Requirement[];
}

function rowsOf(file: RequirementsFile, proofs: ReadonlyMap<string, Proof>): Row[] {
  return CATEGORIES.map((category) => {
    const own = file.requirements.filter((r) => r.category === category);
    const by = (standing: Standing) => own.filter((r) => standingOf(proofs.get(r.id)) === standing);
    return {
      category,
      total: own.length,
      proven: by('proven').length,
      failing: by('failing'),
      unproven: by('unproven'),
    };
  }).filter((row) => row.total > 0);
}

/** The report's Markdown, and a one-line summary for the console. */
export function renderReport(
  file: RequirementsFile,
  proofs: ReadonlyMap<string, Proof>,
): { markdown: string; summary: string } {
  const rows = rowsOf(file, proofs);
  const total = file.requirements.length;
  const proven = rows.reduce((sum, row) => sum + row.proven, 0);
  const overall = `${percent(proven, total)} (${proven} of ${total} requirements proven)`;
  const lines = [
    '# Compatibility',
    '',
    `Generated by \`bun run compat\` from \`spec/requirements.json\` (Claude Code ${file.claudeCode})`,
    'and a run of every test. A requirement is proven when a passing test under `spec(id)` names it',
    '(docs/SPEC.md). Do not edit by hand.',
    '',
    `**Overall: ${overall}.**`,
    '',
    '| Category | Proven | Total | Share |',
    '| --- | ---: | ---: | ---: |',
    ...rows.map(
      (r) => `| ${r.category} | ${r.proven} | ${r.total} | ${percent(r.proven, r.total)} |`,
    ),
    '',
    ...rows.flatMap((row) => detail(row)),
  ];
  return { markdown: `${lines.join('\n')}\n`, summary: `Compatibility: ${overall}` };
}

const list = (items: readonly Requirement[]): string => items.map((r) => `\`${r.id}\``).join(', ');

function detail(row: Row): string[] {
  if (row.failing.length === 0 && row.unproven.length === 0) return [];
  return [
    `## ${row.category}`,
    '',
    ...(row.failing.length > 0 ? [`Failing: ${list(row.failing)}`, ''] : []),
    ...(row.unproven.length > 0 ? [`Unproven: ${list(row.unproven)}`, ''] : []),
  ];
}
